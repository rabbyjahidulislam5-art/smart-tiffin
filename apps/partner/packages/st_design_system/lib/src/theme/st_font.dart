/// Font sizes copied from the legacy widgets. Added in B2 (DD-6).
abstract final class StFont {
  /// Eyebrows.
  static const double micro = 10;

  /// Chips, captions.
  static const double caption = 11;

  /// Labels, small buttons.
  static const double label = 12;

  /// Supporting text in legacy rows.
  static const double small = 13;

  /// Body and row labels.
  static const double body = 14;

  /// Section titles, large buttons.
  static const double bodyLg = 16;

  /// Screen titles.
  static const double title = 17;

  /// Sheet and dialog titles (legacy protect sheet, confirm dialog).
  static const double heading = 18;

  /// Stat values.
  static const double stat = 22;

  /// Hero headings (legacy sign-in title).
  static const double hero = 24;
}
